// Regenerates the Rust wire-contract types in `packages/loca-core-rs/src/contract/`
// from `@loca/shared`, which stays the single source of truth for the contract.
//
//   deno task contract         rewrite the generated modules
//   deno task contract:check   fail if the checked-in output is stale
//
// Two generators feed one typify pass each, partitioned by trust boundary
// (D-003):
//
//   inbound.rs  from Zod, for everything the core validates on the way in.
//               typify carries Zod's .min / .max / .int / .regex into a
//               `Deserialize` that enforces them, so deserializing IS the
//               validation.
//   api.rs      from TypeScript, for everything else: responses, the
//               server->client frames the core produces, and the domain shapes
//               both sides render. Roughly 89% of the contract's types, none of
//               which carry a constraint TypeScript could have expressed.
//
// The check runs in the gate because a stale generated file is otherwise
// invisible: the Rust compiles fine against last week's contract.

import { dirname, fromFileUrl, join } from "@std/path";

import { declareIntegers, INTEGER_FIELDS, type Node } from "./normalise.ts";

const HERE = dirname(fromFileUrl(import.meta.url));
const ROOT = dirname(dirname(HERE));
const OUT_DIR = join(ROOT, "packages", "loca-core-rs", "src", "contract");
const CODEGEN = join(HERE, "codegen", "Cargo.toml");

const check = Deno.args.includes("--check");

function header(source: string): string {
  return [
    "// @generated by `deno task contract`. Do not edit.",
    "//",
    `// Source: ${source}`,
    "// Regenerate after any change to the wire contract in @loca/shared, and",
    "// commit the result. `deno task contract:check` fails when this file is",
    "// stale, because nothing else would notice: the Rust compiles fine against",
    "// an out-of-date contract.",
    "",
    // The crate's clippy restriction lints (unwrap/expect/panic) are about code
    // we write; typify's constraint checks compile a literal regex once in a
    // LazyLock and unwrap it, which cannot fail for a pattern that was valid in
    // Zod. `clippy::all` does not cover restriction lints, hence both lines.
    "#![allow(clippy::all)]",
    "#![allow(clippy::unwrap_used, clippy::expect_used, clippy::panic)]",
    "#![allow(dead_code)]",
    "",
  ].join("\n");
}

/** Captures stdout, for the codegen tool whose stdout is the generated module. */
async function capture(cmd: string, args: string[]): Promise<string> {
  const result = await new Deno.Command(cmd, { args, stdout: "piped", stderr: "inherit" }).output();
  if (!result.success) Deno.exit(1);
  return new TextDecoder().decode(result.stdout);
}

/** For the emitters, whose stdout is the per-pass normalisation counts. Those
 *  counts are how a silently degraded conversion gets noticed. */
async function run(cmd: string, args: string[]): Promise<void> {
  const result = await new Deno.Command(cmd, {
    args,
    stdout: "inherit",
    stderr: "inherit",
  }).output();
  if (!result.success) Deno.exit(1);
}

// Generated types that carry a credential. typify derives `Debug` on every
// type it emits, and the constraint newtypes also `Deref` to their inner
// `String`, so a single `tracing::debug!(?body)` anywhere in the core would put
// a plaintext admin password in `core.log`. Convention across twenty packages
// is not a defense, so the derive is replaced with a redacting `Debug` here,
// once, for everyone.
//
// Keep this list explicit rather than pattern-matched: it is a security
// boundary, and a name-based rule would silently include or exclude types as
// the contract changes. `assertSecretsCovered` below is the tripwire for a NEW
// credential-shaped type that nobody added here.
const SECRET_TYPES = [
  "AdminPasswordSetRequestPassword",
  "ClientRevokeRequestPassword",
  "PairingCodeRequestPassword",
];

// Anything matching this and not in SECRET_TYPES fails the build. `Key` is
// deliberately absent: it matches `LocaJsonToolPermissionsEnvItemKey`, which is
// an environment variable NAME an extension declares, not a value.
const SECRET_SHAPED = /(password|token|secret|apikey|credential)/i;

// Structs carrying a credential in a field of an ordinary type, keyed by the
// Rust field idents to redact.
//
// The newtypes above exist only because a Zod constraint produced one. A field
// the contract declares as a plain `string` gets no newtype, so a name-based
// scan of TYPE names cannot see it, and the most sensitive value on the wire is
// exactly such a field: `PakeFinishResponse.token` is the bearer token minted
// at the end of pairing. Its derived `Debug` would print it in full, and the
// log scrubber cannot help, because a bare token has no surrounding key to
// match on.
const SECRET_FIELDS: Record<string, string[]> = {
  // The client's bearer token for every subsequent request.
  PakeFinishResponse: ["token"],
  // The bearer token a remote MCP server is configured with, on the way to the
  // vault. Write-only on the wire and never echoed back, so this Debug is the
  // only place it could leak.
  McpServerBody: ["auth_token"],
  McpServerPatchBody: ["auth_token"],
};

// Field idents that trip the pattern without carrying a credential. Same
// discipline as NOT_SECRETS: a reason each, never a widened regex.
const NOT_SECRET_FIELDS = new Set([
  // A prompt/completion token COUNT.
  "token_usage",
  // Whether an admin password exists, never the password.
  "admin_password_set",
]);

// Non-credential types whose names trip the pattern. Each one is a deliberate
// exemption with a reason, so the tripwire stays useful instead of being
// widened.
const NOT_SECRETS = new Set([
  // A prompt/completion token count, not an auth token.
  "TokenUsage",
  // The name of an env var an extension declares access to, never its value.
  "LocaJsonToolPermissionsEnvItemKey",
  // A container, not a credential. Its derived `Debug` prints the field's
  // `Debug`, which is the redacting impl above, so `{:?}` on the request yields
  // `AdminPasswordSetRequest { password: AdminPasswordSetRequestPassword(<REDACTED>) }`.
  // That safety is inherited, so it holds only while the field type stays in
  // SECRET_TYPES.
  "AdminPasswordSetRequest",
]);

/** Rewrites the secret types present in `source` and records which ones, so the
 *  caller can assert the whole list was covered across every generated module.
 *  A given module carries only some of them, so a per-module "not found" would
 *  be a false alarm. */
function redactSecrets(source: string, covered: Set<string>): string {
  let out = source;
  for (const name of SECRET_TYPES) {
    if (!new RegExp(`pub struct ${name}\\(`).test(out)) continue;
    covered.add(name);
    const derive = new RegExp(
      `#\\[derive\\(([^)]*)\\)\\]\\n(#\\[serde\\([^\\]]*\\)\\]\\n)?pub struct ${name}\\(`,
      "g",
    );
    const before = out;
    out = out.replace(derive, (_m, derives: string, serdeAttr = "") => {
      const kept = derives
        .split(",")
        .map((d) => d.trim())
        .filter((d) => d !== "Debug")
        .join(", ");
      return `#[derive(${kept})]\n${serdeAttr}pub struct ${name}(`;
    });
    if (out === before) {
      console.error(
        `${name} is declared but its Debug derive did not match the expected shape; ` +
          "typify's output changed and the redaction pass needs updating",
      );
      Deno.exit(1);
    }
    out += `
impl ::std::fmt::Debug for ${name} {
    fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
        f.write_str("${name}(<REDACTED>)")
    }
}
`;
  }
  return out;
}

/** Locates `pub struct <name> { ... }` and returns its span plus its field
 *  idents, so a pass can rewrite the struct without re-parsing the file. */
function findStruct(
  source: string,
  name: string,
): { start: number; end: number; fields: string[] } | null {
  const head = new RegExp(`^pub struct ${name} \\{$`, "m").exec(source);
  if (!head) return null;
  const open = head.index + head[0].length;
  // typify indents every field by four spaces and closes at column zero, so the
  // first line that is exactly `}` ends the struct. No nesting to track.
  const close = source.indexOf("\n}", open);
  if (close < 0) return null;
  const body = source.slice(open, close);
  const fields = [...body.matchAll(/^    pub ([a-z_][a-z_0-9]*):/gm)].map(([, f]) => f);
  return { start: head.index, end: close + 2, fields };
}

/** Replaces the derived `Debug` of every struct in SECRET_FIELDS with one that
 *  prints its ordinary fields and `<REDACTED>` for its credential ones. */
function redactSecretFields(source: string, covered: Set<string>): string {
  let out = source;
  for (const [name, secrets] of Object.entries(SECRET_FIELDS)) {
    const found = findStruct(out, name);
    if (!found) continue;
    covered.add(name);

    const unknown = secrets.filter((f) => !found.fields.includes(f));
    if (unknown.length) {
      console.error(
        `${name} is declared in SECRET_FIELDS with field(s) ${unknown.join(", ")}, ` +
          `but the generated struct has ${found.fields.join(", ")}. The contract changed; ` +
          "update SECRET_FIELDS so the redaction still covers the credential.",
      );
      Deno.exit(1);
    }

    // Strip `Debug` from the derive immediately above the struct.
    const derive = new RegExp(
      `#\\[derive\\(([^)]*)\\)\\]\\n((?:#\\[serde\\([^\\]]*\\)\\]\\n)?)pub struct ${name} \\{`,
    );
    const before = out;
    out = out.replace(derive, (_m, derives: string, serdeAttr: string) => {
      const kept = derives
        .split(",")
        .map((d) => d.trim())
        .filter((d) => d !== "Debug")
        .join(", ");
      return `#[derive(${kept})]\n${serdeAttr}pub struct ${name} {`;
    });
    if (out === before) {
      console.error(
        `${name} carries a credential field but its Debug derive did not match the ` +
          "expected shape; typify's output changed and the redaction pass needs updating",
      );
      Deno.exit(1);
    }

    const lines = found.fields.map((f) =>
      secrets.includes(f)
        ? `            .field("${f}", &"<REDACTED>")`
        : `            .field("${f}", &self.${f})`,
    );
    out += `
impl ::std::fmt::Debug for ${name} {
    fn fmt(&self, f: &mut ::std::fmt::Formatter<'_>) -> ::std::fmt::Result {
        f.debug_struct("${name}")
${lines.join("\n")}
            .finish()
    }
}
`;
  }
  return out;
}

/** Fails the build on a credential-shaped TYPE or FIELD that no pass covers.
 *
 *  Both halves matter and only the first used to be checked. A constraint-free
 *  `string` in the contract generates no newtype, so a name scan over type
 *  declarations is blind to it, and that is where the pairing bearer token
 *  lives. */
// Types typify rendered as the flattened-Option struct rather than an enum,
// and that are KNOWN to be that way. The guard below fails on anything not
// listed, and equally on a listed name that has stopped appearing, so this
// cannot rot into a list of things nobody rechecks.
//
// The tell is a `subtype_0` field. typify models an `anyOf` it cannot tag as a
// struct of `#[serde(flatten)] Option<T>` fields, one per branch, and a
// flattened field cannot absorb a bare scalar, so such a type silently fails
// to deserialize every non-object value the wire carries. It compiles, which is
// the whole problem: the symptom appears in production as
// "invalid type: string, expected struct X".
const UNTAGGED_ALLOWED: Record<string, string> = {};

/** Record every type generated as typify's flattened-Option fallback. */
function collectUntagged(source: string, into: Set<string>): void {
  let current: string | null = null;
  for (const line of source.split("\n")) {
    const decl = /^pub struct (\w+)/.exec(line);
    if (decl) current = decl[1];
    if (current && /^\s*pub subtype_0:/.test(line)) into.add(current);
  }
}

function assertSecretsCovered(source: string): void {
  const missed: string[] = [];

  for (const [, name] of source.matchAll(/^pub (?:struct|enum) ([A-Za-z0-9_]+)/gm)) {
    if (!SECRET_SHAPED.test(name)) continue;
    if (SECRET_TYPES.includes(name) || NOT_SECRETS.has(name)) continue;
    missed.push(`type ${name}`);
  }
  if (missed.length) {
    console.error(
      `credential-shaped generated types with a plain Debug derive: ${missed.join(", ")}.\n` +
        "Add each to SECRET_TYPES in scripts/contract/generate.ts, or to NOT_SECRETS with a reason.",
    );
    Deno.exit(1);
  }

  // A field is covered when its own type is a redacted newtype, or when its
  // struct redacts it by name.
  for (const [, struct] of source.matchAll(/^pub struct ([A-Za-z0-9_]+) \{$/gm)) {
    const found = findStruct(source, struct);
    if (!found) continue;
    const body = source.slice(found.start, found.end);
    for (const [, field, ty] of body.matchAll(/^    pub ([a-z_][a-z_0-9]*): ([^,\n]+)/gm)) {
      if (!SECRET_SHAPED.test(field)) continue;
      if (NOT_SECRET_FIELDS.has(field)) continue;
      if (SECRET_TYPES.some((t) => ty.includes(t))) continue;
      if (SECRET_FIELDS[struct]?.includes(field)) continue;
      missed.push(`${struct}.${field}`);
    }
  }
  if (missed.length) {
    console.error(
      `credential-shaped generated fields printed in full by a derived Debug: ` +
        `${missed.join(", ")}.\n` +
        "Add each to SECRET_FIELDS in scripts/contract/generate.ts, or to " +
        "NOT_SECRET_FIELDS with a reason.",
    );
    Deno.exit(1);
  }
}

/// Inbound request bodies must ignore unknown fields, not reject them.
///
/// ts-json-schema-generator writes `additionalProperties: false` for an
/// interface, so typify puts `deny_unknown_fields` on every generated type. On
/// a DOMAIN type that is useful: it is what makes the untagged unions
/// (`AskUserQuestion` and friends) distinguishable by field set. On an inbound
/// REQUEST body it is a behaviour change, and one the wire policy explicitly
/// rules out: `validation/chat.ts` documents that a newer client adding a field
/// must be processed on the fields the core knows, not rejected, because a
/// rejected body is a 400 where the TypeScript returned 200.
///
/// **This applies to the TypeScript half only, and the distinction is the whole
/// point.** A TypeScript interface has no way to say "open" or "closed", so
/// `additionalProperties: false` there is an artefact of the generator and the
/// policy has to be supplied here. A Zod schema says exactly which one it means:
/// `.passthrough()` for a body that must tolerate a newer client's field,
/// `.strict()` for one that must reject it. Applying this pass to the Zod half
/// overrides the author on the one half where the author was able to speak, and
/// it did: all five pairing bodies are `.strict()` in
/// `validation/pairing.ts` and were silently accepting unknown fields in Rust
/// while the TypeScript core rejected them. On the most security-sensitive
/// boundary in the system, in the direction of accepting more.
///
/// Scoped to a name ending in `Request` so it cannot reach a union variant:
/// those are named `...Subtype0` / `...Item` and keep their strictness.
function relaxRequestBodies(source: string, relaxed: Set<string>): string {
  return source.replace(
    /#\[serde\(deny_unknown_fields\)\]\npub struct ([A-Za-z0-9_]*Request) \{/g,
    (_m, name: string) => {
      relaxed.add(name);
      return `pub struct ${name} {`;
    },
  );
}

/// An optional collection must keep "absent" and "empty" apart.
///
/// typify renders `x?: T[]` as a bare `Vec<T>` carrying `default` plus
/// `skip_serializing_if = "Vec::is_empty"`, which folds the two together in both
/// directions: an absent field deserializes to `[]`, and an empty one serializes
/// to nothing. The type then cannot express a value the contract can, and every
/// such field is a silent drop rather than a compile error.
///
/// It is not hypothetical on either side. `settings.updated`'s `secretNames` is
/// optional meaning "present when the secret set changed", and the client does
/// `if (secretNames) this.configuredSecrets = new Set(secretNames)`, so `[]`
/// clears every "saved" placeholder while absent leaves them alone: deleting the
/// last secret is a frame the collapsed type cannot send. Inbound, `loca.json`'s
/// permission arrays distinguish "not requested" from "requested with no
/// entries", and that difference is what the `--allow-*` derivation is reading.
///
/// So the field becomes `Option<Vec<T>>`, which is exactly what the TypeScript
/// says. serde needs no `default` for an `Option` (a missing field is `None`),
/// and `skip_serializing_if` moves to `Option::is_none`, so `Some(vec![])` goes
/// on the wire as `[]` and `None` stays off it.
function distinguishAbsentFromEmpty(source: string, count: { n: number }): string {
  const EMPTY_CHECK = /^(::std::vec::Vec|::serde_json::Map)::is_empty$/;
  // Which field of which struct was rewritten, so the `defaults` module below
  // can be corrected without guessing from a bare field name.
  const converted = new Map<string, Set<string>>();
  let out = "";
  let i = 0;
  for (;;) {
    const start = source.indexOf("#[serde(", i);
    if (start < 0) {
      out += source.slice(i);
      break;
    }
    const attrEnd = source.indexOf(")]", start);
    if (attrEnd < 0) {
      out += source.slice(i);
      break;
    }
    const attr = source.slice(start, attrEnd + 2);
    const skip = /skip_serializing_if = "([^"]+)"/.exec(attr);
    if (!skip || !EMPTY_CHECK.test(skip[1])) {
      out += source.slice(i, attrEnd + 2);
      i = attrEnd + 2;
      continue;
    }
    // The field declaration follows the attribute: `<ws><name>: <type>,`. The
    // type ends at the first comma outside angle brackets, because a generic
    // argument list is the only nesting a generated field type ever has.
    const decl = /^(\s*(?:pub )?[a-z_][a-z_0-9]*): /.exec(source.slice(attrEnd + 2));
    if (!decl) {
      throw new Error(
        `an is_empty skip is not followed by a field declaration:\n${source.slice(
          start,
          start + 240,
        )}`,
      );
    }
    const typeStart = attrEnd + 2 + decl[0].length;
    let depth = 0;
    let j = typeStart;
    for (; j < source.length; j++) {
      const c = source[j];
      if (c === "<") depth++;
      else if (c === ">") depth--;
      else if (c === "," && depth === 0) break;
    }
    const type = source.slice(typeStart, j);
    const preamble = source.slice(i, start);
    out += preamble;
    // `default` stays: it is redundant for an `Option` (a missing field is
    // already `None`) and rewriting the attribute body risks malforming it.
    out += attr.replace(skip[1], "::std::option::Option::is_none");
    out += `${decl[1]}: ::std::option::Option<${type}>`;
    count.n++;
    i = j;

    // The enclosing struct is whatever `pub struct X {` most recently opened.
    const owner = [...out.matchAll(/pub struct ([A-Za-z0-9_]+) \{/g)].pop();
    const field = decl[1].trim().replace(/^pub /, "");
    if (owner) {
      const fields = converted.get(owner[1]) ?? new Set<string>();
      fields.add(field);
      converted.set(owner[1], fields);
    }
  }

  // typify's `defaults` module builds a struct literal for any schema-level
  // default, filling each of these fields with `vec![]` or an empty map. Those
  // literals no longer typecheck, and the value they mean is `None`: the schema
  // default said the field is absent, which is precisely the distinction this
  // pass just restored. Scoped per struct, so a same-named field on a type that
  // was not rewritten is left alone.
  return out.replace(
    /super::([A-Za-z0-9_]+) \{([^{}]*)\}/g,
    (whole, name: string, body: string) => {
      const fields = converted.get(name);
      if (!fields) return whole;
      const fixed = body.replace(
        /(\n\s*)([a-z_][a-z_0-9]*): (?:vec!\[\]|::serde_json::Map::new\(\))/g,
        (line, ws: string, field: string) =>
          fields.has(field) ? `${ws}${field}: ::std::option::Option::None` : line,
      );
      return `super::${name} {${fixed}}`;
    },
  );
}

// Optional fields that are ALSO `.nullable()`, and therefore keep accepting an
// explicit `null`. Keyed by the JSON property name, with a reason each.
//
// It is empty today and that is a measured fact, not an assumption: the only
// `.nullable()` anywhere under `validation/` is `ws.ts`'s `afterId`, and `ws.ts`
// is deliberately absent from the Zod half (D-006). `assertNullableDeclared`
// below fails the build in BOTH directions, so the first `.nullable()` on an
// inbound body is a decision someone makes here rather than a silent behaviour
// change.
//
// Keyed by property name rather than by `Struct.field` because typify derives
// the names of anonymous nested structs from their JSON pointer path, so there
// is no stable struct name to key on for a field that is not a top-level
// property. The consequence is deliberate over-exclusion: listing a name here
// exempts every field with that name. Prefer a distinct property name to a
// clashing one, and note the clash in the reason if it is unavoidable.
const NULLABLE_FIELDS: Record<string, string> = {};

/** Every optional property of `node` (and, recursively, of everything it
 *  contains) that also admits an explicit `null`. */
function collectNullableOptionals(bundle: Node): Set<string> {
  const $defs = (bundle.$defs ?? {}) as Node;
  const found = new Set<string>();

  const admitsNull = (node: unknown, depth = 0): boolean => {
    if (!node || typeof node !== "object" || depth > 8) return false;
    const n = node as Node;
    if (n.type === "null") return true;
    if (Array.isArray(n.type) && (n.type as unknown[]).includes("null")) return true;
    for (const key of ["anyOf", "oneOf", "allOf"]) {
      const branches = n[key];
      if (Array.isArray(branches) && branches.some((b) => admitsNull(b, depth + 1))) return true;
    }
    const ref = n.$ref;
    if (typeof ref === "string" && ref.startsWith("#/$defs/")) {
      return admitsNull($defs[ref.slice("#/$defs/".length)], depth + 1);
    }
    return false;
  };

  const walk = (node: unknown, seen: Set<unknown>): void => {
    if (!node || typeof node !== "object" || seen.has(node)) return;
    seen.add(node);
    const n = node as Node;
    const props = n.properties as Node | undefined;
    if (props && typeof props === "object") {
      const required = new Set(Array.isArray(n.required) ? (n.required as string[]) : []);
      for (const [name, schema] of Object.entries(props)) {
        if (!required.has(name) && admitsNull(schema)) found.add(name);
      }
    }
    for (const value of Object.values(n)) {
      if (Array.isArray(value)) value.forEach((v) => walk(v, seen));
      else walk(value, seen);
    }
  };

  walk(bundle, new Set());
  return found;
}

/** Fails the build on a nullable optional field nobody declared, and equally on
 *  a declared one the contract no longer has. Same discipline as
 *  UNTAGGED_ALLOWED: a list nobody rechecks is worse than no list. */
function assertNullableDeclared(bundle: Node): void {
  const found = collectNullableOptionals(bundle);
  const undeclared = [...found].filter((name) => !(name in NULLABLE_FIELDS));
  if (undeclared.length) {
    console.error(
      `optional inbound field(s) that also accept null: ${undeclared.join(", ")}.\n` +
        "rejectExplicitNull in scripts/contract/generate.ts would make the generated " +
        "deserializer refuse the `null` the Zod schema accepts, which is a 400 where the " +
        "TypeScript core answers 200. Add each to NULLABLE_FIELDS with a reason, or drop " +
        "the `.nullable()` from the validator.",
    );
    Deno.exit(1);
  }
  const gone = Object.keys(NULLABLE_FIELDS).filter((name) => !found.has(name));
  if (gone.length) {
    console.error(
      `NULLABLE_FIELDS names that are no longer nullable optionals: ${gone.join(", ")}.\n` +
        "The validator dropped the `.nullable()`, so the exemption now only weakens " +
        "validation; drop them from NULLABLE_FIELDS in scripts/contract/generate.ts.",
    );
    Deno.exit(1);
  }
}

/// An optional inbound field must refuse an explicit `null`.
///
/// Zod's `.optional()` means `T | undefined` and REFUSES `null`; admitting null
/// takes `.nullable()`. serde's `Option<T>` accepts `null` and maps it to
/// `None`. So `{"bucket": null}` is a 400 from the TypeScript core and a 200
/// from the port, and it holds for every optional field on every inbound body,
/// pairing included. Confirmed with a `--core=diff` run, not inferred (D-098).
///
/// It cannot be fixed in a route module: after deserialization `null` and absent
/// are both `None`, so nothing downstream can tell them apart. It has to be the
/// generator, and it has to be per field, which is what `deserialize_with`
/// gives: serde calls it only when the key is PRESENT, so absence still falls
/// through to `default` and stays valid, while a present `null` is handed to
/// `T::deserialize` and fails as "invalid type: null".
///
/// **`inbound.rs` only.** `api.rs` describes what the core PRODUCES; nothing
/// deserializes it at a trust boundary, and tightening it would only break the
/// round-trip fixtures.
///
/// Runs AFTER `distinguishAbsentFromEmpty` so it also covers the `Option<Vec<T>>`
/// fields that pass creates: an optional array refuses null in Zod too.
function rejectExplicitNull(source: string, count: { n: number; skipped: Set<string> }): string {
  const SKIP = 'skip_serializing_if = "::std::option::Option::is_none"';
  const HELPER = "crate::contract::inbound::reject_null::option";
  let out = "";
  let i = 0;
  for (;;) {
    const start = source.indexOf("#[serde(", i);
    if (start < 0) {
      out += source.slice(i);
      break;
    }
    const attrEnd = source.indexOf(")]", start);
    if (attrEnd < 0) {
      out += source.slice(i);
      break;
    }
    const attr = source.slice(start, attrEnd + 2);
    // `default` is what makes the field optional rather than nullable-required;
    // without it serde would call the helper for a missing key too, and every
    // absent field would become a hard error.
    const optional = attr.includes(SKIP) && /\bdefault\b/.test(attr);
    const decl = /^(\s*(?:pub )?)([a-z_][a-z_0-9]*): ::std::option::Option</.exec(
      source.slice(attrEnd + 2),
    );
    if (!optional || !decl) {
      out += source.slice(i, attrEnd + 2);
      i = attrEnd + 2;
      continue;
    }
    // The Rust ident is typify's snake_case of the JSON property, so the
    // allowlist (keyed by property name) is matched on the snake_case of each
    // entry rather than by reversing the ident.
    const field = decl[2];
    const exempt = Object.keys(NULLABLE_FIELDS).some((name) => snake(name) === field);
    out += source.slice(i, start);
    out += exempt ? attr : attr.replace(SKIP, `deserialize_with = "${HELPER}", ${SKIP}`);
    if (exempt) count.skipped.add(field);
    else count.n++;
    i = attrEnd + 2;
  }

  return `${out}
/// Rejects an explicit \`null\` for an optional field while still accepting its
/// absence, which is what Zod's \`.optional()\` means and what \`Option<T>\`
/// alone does not (D-098). serde calls this only for a key that is PRESENT, so
/// a missing key still resolves through \`#[serde(default)]\` to \`None\`.
pub mod reject_null {
    pub fn option<'de, D, T>(
        deserializer: D,
    ) -> ::std::result::Result<::std::option::Option<T>, D::Error>
    where
        D: ::serde::Deserializer<'de>,
        T: ::serde::Deserialize<'de>,
    {
        <T as ::serde::Deserialize<'de>>::deserialize(deserializer)
            .map(::std::option::Option::Some)
    }
}
`;
}

// typify embeds the full JSON schema of every type as a `<details>` doc block.
// The schema already lives in @loca/shared; drop the copy.
function stripSchemaDocs(source: string, count: { n: number }): string {
  return source.replace(
    /\n\/\/\/ <details><summary>JSON schema<\/summary>\n(?:\/\/\/.*\n)*?\/\/\/ <\/details>/g,
    () => {
      count.n++;
      return "";
    },
  );
}

// `impl From<&T> for T { value.clone() }` exists for typify's builder pattern,
// which is off, and the `TryFrom<&String>` / `TryFrom<String>` enum shims only
// delegate to `parse()`. Nothing calls either. Runs on rustfmt output, where a
// top-level impl always ends at the first `\n}\n`.
function stripCloneAndStringShims(source: string, count: { n: number }): string {
  const block = (head: string) =>
    new RegExp(`^impl ::std::convert::${head} for \\w+ \\{\\n(?:.*\\n)*?\\}\\n`, "gm");
  const drop = (re: RegExp, body: string) => (text: string) =>
    text.replace(re, (m) => {
      if (!m.includes(body)) return m;
      count.n++;
      return "";
    });
  return drop(
    block("TryFrom<&?::std::string::String>"),
    "value.parse()",
  )(drop(block("From<&(?:Self|\\w+)>"), "value.clone()")(source));
}

function snake(name: string): string {
  return name.replace(/([a-z0-9])([A-Z])/g, "$1_$2").toLowerCase();
}

/** typify formats its output with prettyplease, which does not agree with
 *  rustfmt. `deno task fmt` runs `cargo fmt` over the whole crate, so without
 *  this the generated files get rewritten the moment anyone formats and the
 *  staleness check then fails forever. Emitting the rustfmt-stable form makes
 *  `cargo fmt` a no-op on them. */
async function rustfmt(source: string): Promise<string> {
  const proc = new Deno.Command("rustfmt", {
    args: ["--edition", "2021", "--emit", "stdout", "--quiet"],
    stdin: "piped",
    stdout: "piped",
    stderr: "inherit",
  }).spawn();
  const writer = proc.stdin.getWriter();
  await writer.write(new TextEncoder().encode(source));
  await writer.close();
  const result = await proc.output();
  if (!result.success) Deno.exit(1);
  return new TextDecoder().decode(result.stdout);
}

const tmp = await Deno.makeTempDir({ prefix: "loca-contract-" });
try {
  const targets = [
    {
      name: "inbound.rs",
      // Zod says which bodies are open and which are closed, so the relaxation
      // pass must not run here. See relaxRequestBodies.
      relaxRequests: false,
      // Zod's `.optional()` refuses `null`; `Option<T>` alone does not. See
      // rejectExplicitNull.
      rejectNull: true,
      schema: join(tmp, "inbound.schema.json"),
      emitter: join(HERE, "emit-zod.ts"),
      source: "packages/loca-shared/src/validation/*.ts (Zod), via z.toJSONSchema + typify",
    },
    {
      name: "api.rs",
      relaxRequests: true,
      rejectNull: false,
      schema: join(tmp, "api.schema.json"),
      emitter: join(HERE, "emit-ts.ts"),
      source: "packages/loca-shared/src/{api,domain}/*.ts, via ts-json-schema-generator + typify",
    },
  ];

  let stale = 0;
  const redacted = new Set<string>();
  const relaxed = new Set<string>();
  const optionalCollections = { n: 0 };
  const stripped = { n: 0 };
  const shims = { n: 0 };
  const nullRejecting = { n: 0, skipped: new Set<string>() };

  // Fixtures ride along with the generated types: they are emitted from the
  // same Zod schemas, so a contract change that invalidates one invalidates
  // both, and the staleness check has to cover them together.
  const fixturePath = join(ROOT, "packages", "loca-core-rs", "tests", "fixtures", "contract.json");
  const fixtureTmp = join(tmp, "contract.json");
  await run(Deno.execPath(), ["run", "-A", join(HERE, "emit-fixtures.ts"), fixtureTmp]);
  const fixtures = await Deno.readTextFile(fixtureTmp);
  // Compared by content, not by bytes: `deno task fmt` runs oxfmt over the repo
  // and reformats this file. Byte comparison would then report it stale after
  // every format, and rewriting it would put the two tools in a loop.
  const canonical = (text: string | null): string | null => {
    try {
      return text === null ? null : JSON.stringify(JSON.parse(text));
    } catch {
      return null;
    }
  };
  /** Write `emitted` to `path`, or report it stale under --check. */
  async function syncJson(name: string, path: string, emitted: string): Promise<void> {
    if (canonical(await Deno.readTextFile(path).catch(() => null)) === canonical(emitted)) {
      console.log(`ok   ${name} (up to date)`);
      return;
    }
    if (check) {
      console.error(`stale ${name}: run \`deno task contract\` and commit the result`);
      stale++;
      return;
    }
    await Deno.mkdir(dirname(path), { recursive: true });
    await Deno.writeTextFile(path, emitted);
    console.log(`wrote ${name}`);
  }

  await syncJson("contract.json", fixturePath, fixtures);

  // The settings schema reaches the core as DATA, not as generated Rust: it is
  // pure JSON (no functions anywhere in the schema types), and the core reads a
  // projection of it carrying only what PATCH validation and default resolution
  // need. Same staleness hazard as the types above, and it is the reason this
  // runs here rather than by hand: the Rust compiles fine against last week's
  // schema, so a new setting would silently be unknown to validation and absent
  // from the resolved defaults.
  const settingsPath = join(ROOT, "packages", "loca-core-rs", "src", "settings", "schema.json");
  const settingsTmp = join(tmp, "settings-schema.json");
  await run(Deno.execPath(), ["run", "-A", join(HERE, "emit-settings-schema.ts"), settingsTmp]);
  await syncJson("settings/schema.json", settingsPath, await Deno.readTextFile(settingsTmp));

  // The dev-channel catalog and the canonicalisation fixture, same reason and
  // same hazard as the settings schema above: Rust cannot import a TypeScript
  // module, so the payload reaches the core as data, and the core compiles fine
  // against last week's copy. A model added to the authoring package would be
  // silently absent from every dev core and from every test built on one,
  // including the fit suite whose assertions name concrete models.
  //
  // **This block is D-160.** Both files carried `"generatedBy": "deno task
  // contract, via .../emit-catalog.ts"` while NOTHING ran that emitter, so the
  // artifacts asserted a provenance they did not have, and three source files
  // repeated the claim. The repetition read as corroboration and was not: each
  // was written by someone reading one of the others, so all three had a single
  // unchecked source. The Rust fit suite was asserting against a catalog the
  // TypeScript core no longer compiled, with `deno task check` green throughout.
  //
  // The emitter's Ed25519 seed is fixed (`emit-catalog.ts`), so its output is
  // stable across runs and the only drift this reports is a real catalog or
  // `canonicalize` change.
  const catalogPath = join(ROOT, "packages", "loca-core-rs", "src", "models", "catalog.dev.json");
  const vectorsPath = join(
    ROOT,
    "packages",
    "loca-core-rs",
    "src",
    "models",
    "testdata",
    "canonical-vectors.json",
  );
  const catalogTmp = join(tmp, "catalog.dev.json");
  const vectorsTmp = join(tmp, "canonical-vectors.json");
  await run(Deno.execPath(), ["run", "-A", join(HERE, "emit-catalog.ts"), catalogTmp, vectorsTmp]);
  await syncJson("models/catalog.dev.json", catalogPath, await Deno.readTextFile(catalogTmp));
  await syncJson(
    "models/testdata/canonical-vectors.json",
    vectorsPath,
    await Deno.readTextFile(vectorsTmp),
  );

  // Which allowlisted field names were actually found, unioned across both
  // bundles: a name lives in only one of them as often as in both.
  const integers = new Map<string, number>();
  const untagged = new Set<string>();

  for (const target of targets) {
    await run(Deno.execPath(), ["run", "-A", target.emitter, target.schema]);
    // Runs here rather than inside the emitters because its tripwire spans both
    // bundles: `expiresAtMs` exists only in the TypeScript half and `weekdays`
    // is already `.int()` in the Zod half, so neither emitter alone can tell a
    // name that covered nothing from one that covered the other bundle.
    const bundle = JSON.parse(await Deno.readTextFile(target.schema)) as Node;
    if (target.rejectNull) assertNullableDeclared(bundle);
    const covered = declareIntegers(bundle);
    for (const [name, n] of covered) integers.set(name, (integers.get(name) ?? 0) + n);
    console.log(
      `int: ${covered.size} field name(s) declared integer at ` +
        `${[...covered.values()].reduce((a, b) => a + b, 0)} site(s) in ${target.name}`,
    );
    await Deno.writeTextFile(target.schema, JSON.stringify(bundle, null, 2));
    const raw = await capture("cargo", [
      "run",
      "-q",
      // --locked so a drifted codegen lockfile cannot change the generated
      // types under us, the same rule the shipped crates follow in CI.
      "--locked",
      "--manifest-path",
      CODEGEN,
      "--",
      target.schema,
      header(target.source),
    ]);
    assertSecretsCovered(raw);
    collectUntagged(raw, untagged);
    const slim = stripSchemaDocs(raw, stripped);
    const redactedSource = redactSecretFields(redactSecrets(slim, redacted), redacted);
    const collections = distinguishAbsentFromEmpty(
      target.relaxRequests ? relaxRequestBodies(redactedSource, relaxed) : redactedSource,
      optionalCollections,
    );
    const generated = stripCloneAndStringShims(
      await rustfmt(
        target.rejectNull ? rejectExplicitNull(collections, nullRejecting) : collections,
      ),
      shims,
    );

    const path = join(OUT_DIR, target.name);
    const current = await Deno.readTextFile(path).catch(() => null);
    if (current === generated) {
      console.log(`ok   ${target.name} (up to date)`);
      continue;
    }
    if (check) {
      console.error(`stale ${target.name}: run \`deno task contract\` and commit the result`);
      stale++;
      continue;
    }
    await Deno.writeTextFile(path, generated);
    console.log(`wrote ${target.name}`);
  }

  // The pass above is the only thing keeping an optional collection expressible,
  // and it is a text rewrite over typify's rendering. If typify stops emitting
  // the shape it looks for, the rewrite quietly applies to nothing and every
  // optional array silently collapses again, which compiles and passes the
  // fixtures. The contract has had optional collections since before the port
  // began, so zero means the pass broke, not that the contract changed.
  if (!optionalCollections.n) {
    console.error(
      "the optional-collection pass rewrote nothing. typify's rendering of an " +
        "optional array changed, so `absent` and `[]` are folding together " +
        "again; update distinguishAbsentFromEmpty in scripts/contract/generate.ts.",
    );
    Deno.exit(1);
  }
  console.log(`ok   ${optionalCollections.n} optional collection(s) kept distinct from empty`);

  // Same guard: a typify rendering change would leave the schema docs and the
  // conversion shims in place, doubling the file with nothing going red.
  if (!stripped.n || !shims.n) {
    console.error(
      "the doc/shim stripping pass rewrote nothing. typify's rendering changed; " +
        "update stripSchemaDocs / stripCloneAndStringShims in scripts/contract/generate.ts.",
    );
    Deno.exit(1);
  }
  console.log(`ok   ${stripped.n} schema doc block(s) and ${shims.n} conversion shim(s) stripped`);

  // Same hazard, same guard: the rewrite keys off typify's rendering of an
  // optional field, so if that rendering changes the pass silently applies to
  // nothing and every optional inbound field goes back to accepting `null`,
  // which compiles and passes the fixtures. The inbound contract has had
  // optional fields since before the port began, so zero means the pass broke.
  if (!nullRejecting.n) {
    console.error(
      "the null-rejection pass rewrote nothing. typify's rendering of an optional " +
        "field changed, so every optional inbound field accepts an explicit `null` " +
        "the Zod oracle refuses again (D-098); update rejectExplicitNull in " +
        "scripts/contract/generate.ts.",
    );
    Deno.exit(1);
  }
  console.log(
    `ok   ${nullRejecting.n} optional inbound field(s) reject an explicit null` +
      (nullRejecting.skipped.size
        ? `, ${nullRejecting.skipped.size} nullable field(s) exempt: ` +
          `${[...nullRejecting.skipped].join(", ")}`
        : ""),
  );

  // Every allowlisted field name must have rewritten at least one `number`. A
  // name that rewrites nothing is a field the contract renamed or removed, and
  // the declaration silently stopped applying: the type reverts to `f64`, the
  // Rust still compiles, and the only symptom is a `.0` back on the wire.
  const uncoveredIntegers = [...INTEGER_FIELDS.keys()].filter((name) => !integers.has(name));
  if (uncoveredIntegers.length) {
    console.error(
      `integer field names that matched no \`number\` in either bundle: ` +
        `${uncoveredIntegers.join(", ")}.\n` +
        "They were renamed or removed from the contract, so those fields are back to f64; " +
        "update INTEGER_FIELDS in scripts/contract/normalise.ts.",
    );
    Deno.exit(1);
  }
  console.log(
    `ok   ${integers.size} field name(s) declared integer at ` +
      `${[...integers.values()].reduce((a, b) => a + b, 0)} site(s)`,
  );

  // A union that lost its tag deserializes almost nothing, and it does it
  // while compiling cleanly, so nothing downstream notices until a real
  // payload arrives. Both directions are failures: a NEW name means a
  // normalisation pass stopped covering a union (this is how `WsFrame`
  // regressed into a struct while pass 3 was being narrowed), and a name that
  // has STOPPED appearing means the entry is stale and the list is drifting
  // away from what it claims to describe.
  const newUntagged = [...untagged].filter((name) => !(name in UNTAGGED_ALLOWED));
  if (newUntagged.length) {
    console.error(
      `union(s) generated as typify's flattened-Option struct: ${newUntagged.join(", ")}.\n` +
        "That type cannot deserialize a non-object branch and will fail at runtime with " +
        '"invalid type: ..., expected struct". A normalisation pass in ' +
        "scripts/contract/normalise.ts stopped covering it; fix the pass, or add the name " +
        "to UNTAGGED_ALLOWED with the reason if it is genuinely unfixable.",
    );
    Deno.exit(1);
  }
  const goneUntagged = Object.keys(UNTAGGED_ALLOWED).filter((name) => !untagged.has(name));
  if (goneUntagged.length) {
    console.error(
      `UNTAGGED_ALLOWED names no longer generated that way: ${goneUntagged.join(", ")}.\n` +
        "They were fixed or removed; drop them from UNTAGGED_ALLOWED in " +
        "scripts/contract/generate.ts so the list keeps meaning what it says.",
    );
    Deno.exit(1);
  }
  console.log(`ok   ${untagged.size} known untagged union(s), no new ones`);

  // Every declared secret type must have been found in exactly one module. A
  // missing one means the contract moved it or renamed it, and the redaction
  // silently stopped applying.
  const uncovered = [...SECRET_TYPES, ...Object.keys(SECRET_FIELDS)].filter(
    (name) => !redacted.has(name),
  );
  if (uncovered.length) {
    console.error(
      `secret types never found in any generated module: ${uncovered.join(", ")}.\n` +
        "They were renamed or removed from the contract; update SECRET_TYPES or " +
        "SECRET_FIELDS in scripts/contract/generate.ts.",
    );
    Deno.exit(1);
  }
  console.log(
    `ok   ${SECRET_TYPES.length} credential type(s) and ` +
      `${Object.values(SECRET_FIELDS).flat().length} credential field(s) redacted`,
  );

  if (relaxed.size) {
    console.log(`relaxed ${relaxed.size} inbound request bodies to ignore unknown fields`);
  }

  if (stale) Deno.exit(1);
} finally {
  await Deno.remove(tmp, { recursive: true });
}
