// Regenerates the on-disk parity fixture for D2.
//
// Drives the REAL Deno `SessionsRepo` against a throwaway root and copies the
// resulting `sessions/` tree into the Rust crate's testdata. The committed tree
// is the artefact; this script exists so it can be regenerated when the shape
// legitimately changes, and so nobody has to hand-write a file that is supposed
// to prove what the other implementation actually writes.
//
// Run from the repo root:
//
//   deno run -A scripts/parity/session-fixture.ts
//
// The `sessions/` tree is one of the byte-exact parity surfaces, so the point of
// the fixture is coverage of the awkward parts rather than of the happy path:
// every message role the union carries, a multipart user message, a session with
// a token usage, an attachment record, and a second owner so the Rust tests can
// assert owner scoping against a tree they did not write.

import { join } from "@std/path";
import { attachHost } from "@loca/core-engine";
import { sessionsRepo } from "@loca/core-engine/services/sessions-store";
import { denoHost } from "../../packages/loca-core/src/host/deno-host.ts";
import type { Message } from "@loca/shared";

const OUT = join(Deno.cwd(), "packages/loca-core-rs/src/sessions/testdata/deno-sessions");

const root = await Deno.makeTempDir({ prefix: "loca-d2-fixture-" });
Deno.env.set("LOCA_CORE_HOME", root);
attachHost(denoHost());

const repo = sessionsRepo();
const alice = "client-alice";
const bob = "client-bob";

// A session covering every role, so the Rust reader is exercised against the
// whole union rather than against user and assistant alone.
const main = await repo.create({ ownerClientId: alice, title: "Parity fixture" });
const roles: Message[] = [
  { role: "user", content: "What is the weather?" } as Message,
  {
    role: "user",
    content: [
      { type: "text", text: "And in this photo?" },
      {
        type: "image_file",
        filename: "photo.png",
        path: "/api/v1/sessions/x/attachments/a1",
        mime: "image/png",
      },
    ],
  } as Message,
  { role: "reasoning", content: "The user wants weather.", interrupted: false } as Message,
  {
    role: "assistant",
    content: "It is 31 degrees.",
    toolCalls: [
      {
        callId: "call-1",
        extensionId: "loca-extension-builtin",
        toolName: "get_weather",
        arguments: '{"city":"Jakarta"}',
        status: "completed",
      },
    ],
  } as Message,
  {
    role: "tool",
    callId: "call-1",
    extensionId: "loca-extension-builtin",
    toolName: "get_weather",
    arguments: '{"city":"Jakarta"}',
    status: "completed",
    result: { tempC: 31 },
  } as Message,
  { role: "system", content: "You are helpful." } as Message,
  { role: "tool_filter", status: "complete", toolsSent: 3 } as Message,
  { role: "memory_filter", status: "complete" } as Message,
  { role: "display", content: { type: "markdown", markdown: "**done**" } } as Message,
  { role: "error", content: "something failed", code: "provider_error" } as Message,
];
for (const message of roles) await repo.appendMessage(main.id, message);
await repo.setTokenUsage(main.id, { prompt: 120, completion: 45, total: 165 });

// An attachment record, with real bytes beside it so the footprint the storage
// screen reports is assertable rather than assumed.
const attachmentsDir = join(root, "sessions", main.id, "attachments");
await Deno.mkdir(attachmentsDir, { recursive: true });
const attachmentPath = join(attachmentsDir, "att1_photo.png");
await Deno.writeFile(attachmentPath, new Uint8Array(64).fill(7));
await repo.recordAttachment(main.id, "msg-1", "photo.png", "image/png", 64, attachmentPath);

// A second owner, so owner scoping is asserted against a session the Rust side
// did not create.
const other = await repo.create({ ownerClientId: bob, title: "Bob's session" });
await repo.appendMessage(other.id, { role: "user", content: "hello from bob" } as Message);

// An empty session, which is what a client that opened a window and typed
// nothing leaves behind.
await repo.create({ ownerClientId: alice, title: "" });

await Deno.remove(OUT, { recursive: true }).catch(() => {});
await Deno.mkdir(OUT, { recursive: true });
for await (const entry of Deno.readDir(join(root, "sessions"))) {
  await copyDir(join(root, "sessions", entry.name), join(OUT, entry.name));
}

// The ids are ULIDs, so they differ on every run. The Rust tests read them from
// the tree rather than hardcoding them, except for the two the manifest names.
await Deno.writeTextFile(
  join(OUT, "..", "deno-sessions.json"),
  JSON.stringify(
    {
      note: "Generated by scripts/parity/session-fixture.ts. Do not hand-edit.",
      aliceClientId: alice,
      bobClientId: bob,
      mainSessionId: main.id,
      otherSessionId: other.id,
      mainMessageCount: roles.length,
      mainRoles: roles.map((m) => m.role),
    },
    null,
    2,
  ) + "\n",
);

console.log(`wrote ${OUT}`);

async function copyDir(from: string, to: string): Promise<void> {
  await Deno.mkdir(to, { recursive: true });
  for await (const entry of Deno.readDir(from)) {
    const src = join(from, entry.name);
    const dst = join(to, entry.name);
    if (entry.isDirectory) await copyDir(src, dst);
    else await Deno.copyFile(src, dst);
  }
}
